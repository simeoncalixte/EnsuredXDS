import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import Ajv from 'ajv';
import standaloneCode from 'ajv/dist/standalone/index.js';
import { generateComponentManifest } from './component-manifest.mjs';

const root = new URL('../', import.meta.url);
const manifest = generateComponentManifest({
  tsconfigPath: fileURLToPath(new URL('tsconfig.build.json', root)),
  componentsDirectory: fileURLToPath(new URL('src/components', root)),
  registry: JSON.parse(readFileSync(new URL('schema/component-registry.json', root), 'utf8')),
});
const ajv = new Ajv({ allErrors: true, strict: false, code: { source: true, esm: true } });
const exports = {};
const components = [
  'result-metric-card',
  'loss-ratio-trajectory',
  'allocation-list',
  'nat-cat-risk-banner',
  'treaty-renewal-watchlist',
  'submission-pipeline-overview',
  'appetite-distribution',
  'sla-velocity-panel',
  'priority-underwriter-queue',
];
for (const name of components) {
  const id = `xds.${name}`;
  const component = manifest.components.find((entry) => entry.id === id);
  if (!component) throw new Error(`Missing dashboard component: ${id}`);
  const schema = structuredClone(component.propsSchema);
  if (name === 'result-metric-card') {
    schema.properties.value = { anyOf: [{ type: 'string' }, { type: 'null' }] };
    schema.required = [...(schema.required ?? []), 'value'];
  }
  ajv.addSchema(schema, id);
  exports[name.replace(/-([a-z])/g, (_, letter) => letter.toUpperCase())] = id;
}
const directory = new URL('src/validation/', root);
mkdirSync(directory, { recursive: true });
writeFileSync(
  new URL('dashboardValidators.generated.ts', directory),
  '// @ts-nocheck\n// Generated by scripts/generate-dashboard-validators.mjs. Do not edit.\n' +
    standaloneCode(ajv, exports) +
    '\n',
);
console.log(`Generated ${components.length} standalone dashboard validators.`);
