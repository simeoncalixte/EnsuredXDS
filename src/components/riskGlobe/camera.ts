const mix = (a: number, b: number, t: number) => a + (b - a) * t;
const ease = (t: number) => t * t * (3 - 2 * t);
export function cameraAt(shot: number, progress: number, seat: GlobeSeat): CameraKey {
  const cut = cameras[seat === 'everyone' ? 'broker' : seat];
  const index = Math.max(0, Math.min(5, shot - 1));
  const keys = cut[index];
  const previous = index > 0 ? cut[index - 1][2] : K(24, -32, 4, [0, 0, 0]);
  let a: CameraKey, b: CameraKey, t: number;
  if (progress < 0.15) {
    a = previous;
    b = keys[0];
    t = ease(progress / 0.15);
  } else {
    const u = (progress - 0.15) / 0.85;
    if (u < 0.45) {
      a = keys[0];
      b = keys[1];
      t = ease(u / 0.45);
    } else {
      a = keys[1];
      b = keys[2];
      t = ease((u - 0.45) / 0.55);
    }
  }
  return {
    lat: mix(a.lat, b.lat, t),
    lon: mix(a.lon, b.lon, t),
    d: mix(a.d, b.d, t),
    fov: mix(a.fov, b.fov, t),
    look: [
      mix(a.look[0], b.look[0], t),
      mix(a.look[1], b.look[1], t),
      mix(a.look[2], b.look[2], t),
    ],
  };
}
